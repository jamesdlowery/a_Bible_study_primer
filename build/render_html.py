#!/usr/bin/env python3
"""
Render build/full_document_<fmt>.md (the html target) to a standalone HTML5
file.

Converting the entire document to HTML in a single pandoc invocation
triggers pathological (worse-than-linear) behavior in pandoc's HTML writer.
Confirmed empirically while diagnosing a build failure: converting ~200 of
the ~1,460 near-identical "Reportedly Contradicting Passages" sub-documents
to HTML takes ~15s, but ~500 of them don't finish in 150s, and the full
document reliably gets OOM-killed. DOCX/ODT are unaffected -- the same
total content converts to DOCX in about a minute with stable memory -- so
this is specific to the HTML writer (most likely something in its
heading-id/anchor bookkeeping that scales badly with the sheer number of
near-duplicate headings in one document, though the exact pandoc-internal
mechanism wasn't conclusively isolated; disabling the link_attributes
extension and converting the duplicate-prone sub-headings to plain bold
text were both tried and neither fixed it, so the workaround here avoids
the problem rather than eliminating its root cause).

The fix: split the document into N chunks at existing page-break
boundaries (so no chunk ever splits mid-structure -- every target in the
document is already wrapped in a print-page-break div), convert each chunk
to an HTML *fragment* (no --standalone) separately, then assemble all
fragments inside a standalone HTML5 shell generated by pandoc itself (so
the <head>, styling, and template output are byte-identical to what a
single-pass --standalone conversion would have produced).

Also builds a left-hand sidebar navigation matching the depth of the
PDF version's own bookmarks panel (confirmed directly: 6 levels, 1919
entries, down to individual claim/difference headings within each book,
not just book-level) -- a nested, collapsed-by-default <details>/
<summary> tree built directly from every <h1>-<h6> tag's own level in
the already-rendered HTML, the same outline-from-heading-levels
algorithm a PDF viewer's own bookmarks panel is built from. No
JavaScript: native <details> handles expand/collapse and native anchor
links handle jump-to-section. Not real HTML frames -- those are
deprecated, require splitting into multiple files, and don't fit this
project's one-self-contained-file design; this is a fixed-position CSS
sidebar instead, functionally equivalent but built the way a modern
browser expects.

Usage: python3 render_html.py <full_document_md> <html_style_path> <out_html_path>
"""
import sys
import re
import html as html_entities
import subprocess

PANDOC_READER = "markdown+raw_attribute+link_attributes-yaml_metadata_block"
PAGEBREAK_MARKER = '<div class="print-page-break"></div>'
HEADING_RE = re.compile(r'<(h[1-6])[^>]*\bid="([^"]+)"[^>]*>(.*?)</\1>', re.DOTALL)

# ~1.5MB per chunk. Comfortably below the ~5.8MB/15s point on the observed
# scaling curve, with a wide safety margin against the non-linear blowup
# that shows up somewhere between 5.8MB and 12.4MB.
CHUNK_TARGET_CHARS = 1_500_000


def split_into_chunks(content, target_chars):
    """Split on page-break boundaries, grouping consecutive pieces into
    chunks of roughly target_chars each. Every chunk boundary falls exactly
    on an existing page-break marker, so this never splits mid-structure
    (mid-table, mid-raw-block, etc.)."""
    pieces = content.split(PAGEBREAK_MARKER)
    chunks = []
    current = [pieces[0]]
    current_len = len(pieces[0])
    for piece in pieces[1:]:
        piece_with_marker = PAGEBREAK_MARKER + piece
        if current_len >= target_chars:
            chunks.append("".join(current))
            current = [piece_with_marker]
            current_len = len(piece_with_marker)
        else:
            current.append(piece_with_marker)
            current_len += len(piece_with_marker)
    if current:
        chunks.append("".join(current))
    return chunks


def pandoc_to_html_fragment(md_text):
    result = subprocess.run(
        ["pandoc", "-f", PANDOC_READER, "--wrap=none", "-t", "html5"],
        input=md_text, capture_output=True, text=True, check=True,
    )
    return result.stdout


def build_standalone_shell(title, html_style_path):
    """Get pandoc's own standalone-HTML5 template output (doctype, head,
    styling, etc.) around a unique placeholder paragraph, then split on
    that placeholder -- so the final document's wrapper is byte-identical
    to what a single-pass --standalone conversion would have produced,
    without having to hand-maintain a copy of pandoc's default template."""
    placeholder = "ZZZ_RENDER_HTML_BODY_PLACEHOLDER_ZZZ"
    result = subprocess.run(
        ["pandoc", "-f", "markdown", "-t", "html5", "--standalone",
         f"--metadata=title={title}",
         f"--include-in-header={html_style_path}"],
        input=placeholder, capture_output=True, text=True, check=True,
    )
    shell = result.stdout
    marker = f"<p>{placeholder}</p>"
    if marker not in shell:
        raise RuntimeError(
            "Could not find the body placeholder in pandoc's standalone "
            "shell output -- pandoc's default HTML template may have "
            "changed in a way this script doesn't account for."
        )
    before, after = shell.split(marker)
    return before, after


ID_ATTR_RE = re.compile(r'\bid="([^"]+)"')


def dedupe_ids_across_chunks(body_html):
    """Pandoc de-duplicates repeated heading text ("New Testament" appears
    as its own heading under both Manuscript and Translation Differences
    and Reportedly Contradicting Passages, for instance) by appending
    "-1", "-2" suffixes to later occurrences -- but only within a single
    pandoc invocation. Converting the document in separate chunks (see
    module docstring) means each chunk's own pandoc call starts that
    numbering over from scratch, so the same text repeated in two
    different chunks collides on the identical id in both -- confirmed
    directly: 119 ids each shared by 2+ headings after chunked
    conversion. A genuine, user-visible bug, not just a sidebar
    cosmetic issue: a duplicate id is invalid HTML, and a browser's
    native anchor-jump always goes to the *first* element with a given
    id, so clicking a link meant for the second occurrence would
    silently land on the first instead.

    Fixed here, once, directly on the assembled HTML string, in the same
    place-first-occurrence-keeps-the-name/suffix-later-ones convention
    pandoc itself already uses -- so any existing hardcoded href to a
    base (un-suffixed) id, like the "Back to Table of Contents" links'
    own #table-of-contents, keeps resolving to the same first occurrence
    it always has, while later occurrences get a distinct id of their
    own for the sidebar (built from this corrected HTML) to link to
    correctly.

    Picking a free suffix means checking against every id already in the
    document, not just counting same-text occurrences: pandoc's own
    in-chunk dedup can independently produce e.g. "new-testament-1" for
    an unrelated heading in the same chunk, which collides with the
    naive next-count guess for a genuine cross-chunk duplicate of
    "New Testament" -- confirmed directly as a real, if smaller, second
    wave of collisions (15) from a first version of this fix that just
    counted occurrences without checking for that."""
    all_ids = set(ID_ATTR_RE.findall(body_html))
    used = set(all_ids)
    seen_base = set()

    def replace(m):
        original = m.group(1)
        if original not in seen_base:
            seen_base.add(original)
            return m.group(0)
        n = 1
        candidate = f"{original}-{n}"
        while candidate in used:
            n += 1
            candidate = f"{original}-{n}"
        used.add(candidate)
        return f'id="{candidate}"'

    return ID_ATTR_RE.sub(replace, body_html)


def extract_headings(body_html):
    """Every <hN id="..."> in document order, as (level, anchor, text).
    Mirrors what a PDF viewer's bookmarks panel is built from (heading
    levels), and what assemble.py's own resolve_anchors() already
    extracts the same way for its Table of Contents links -- but walking
    every heading here, not just ones matching a known target's title, so
    this reaches the same depth the PDF's own bookmarks do (confirmed
    directly: 6 levels, 1919 entries, down to individual claim/difference
    headings within each book, not just book-level)."""
    headings = []
    for m in HEADING_RE.finditer(body_html):
        level = int(m.group(1)[1])
        anchor = m.group(2)
        text = re.sub(r'<[^>]+>', '', m.group(3))
        text = html_entities.unescape(text).replace("\n", " ").strip()
        if text:
            headings.append((level, anchor, text))
    return headings


def build_heading_tree(headings):
    """Standard outline-from-heading-levels algorithm (the same one a PDF
    viewer's own bookmark panel is built from): a heading of level N
    becomes a child of the nearest preceding heading with a lower level.
    Returns a list of {"anchor", "text", "children"} nodes."""
    root = []
    stack = [(0, root)]
    for level, anchor, text in headings:
        while stack and stack[-1][0] >= level:
            stack.pop()
        node = {"anchor": anchor, "text": text, "children": []}
        stack[-1][1].append(node)
        stack.append((level, node["children"]))
    return root


def render_sidebar_tree(nodes):
    """Nested <details>/<summary> tree, collapsed by default -- the same
    click-to-expand interaction as a PDF viewer's bookmarks panel. Each
    node's own label is a real link (jumps to that heading) whether or
    not it also has children to expand; browsers correctly dispatch a
    click on the nested <a> as navigation and a click elsewhere in the
    <summary> (e.g. the disclosure triangle) as toggling, so both
    behaviors coexist without conflict."""
    parts = []
    for node in nodes:
        label = html_entities.escape(node["text"])
        link = f'<a href="#{node["anchor"]}">{label}</a>'
        if node["children"]:
            parts.append(f"<details><summary>{link}</summary><div class=\"sidebar-children\">")
            parts.append(render_sidebar_tree(node["children"]))
            parts.append("</div></details>")
        else:
            parts.append(f'<div class="sidebar-leaf">{link}</div>')
    return "".join(parts)


def build_sidebar_nav(body_html):
    headings = extract_headings(body_html)
    tree = build_heading_tree(headings)
    inner = render_sidebar_tree(tree)
    return f'<nav class="sidebar" aria-label="Document bookmarks">{inner}</nav>'


def main():
    if len(sys.argv) != 4:
        sys.exit(f"Usage: {sys.argv[0]} <full_document_md> <html_style_path> <out_html_path>")
    full_md_path, html_style_path, out_path = sys.argv[1:4]

    with open(full_md_path, encoding="utf-8") as f:
        content = f.read()

    chunks = split_into_chunks(content, CHUNK_TARGET_CHARS)
    print(f"Split into {len(chunks)} chunks for HTML conversion.")

    fragments = []
    for i, chunk in enumerate(chunks, 1):
        print(f"Converting chunk {i}/{len(chunks)} ({len(chunk)} chars)...")
        fragments.append(pandoc_to_html_fragment(chunk))

    body_html = "".join(fragments)

    print("De-duplicating heading ids across chunk boundaries...")
    body_html = dedupe_ids_across_chunks(body_html)

    print("Building sidebar navigation from heading structure...")
    sidebar_html = build_sidebar_nav(body_html)

    before, after = build_standalone_shell("A Bible Study Primer", html_style_path)
    # A two-column layout (fixed sidebar + main content), not real HTML
    # frames -- frames are deprecated, require splitting into multiple
    # files, and don't fit this project's one-self-contained-file design.
    # The wrapper div and sidebar are injected here (after all fragments
    # are already assembled), not earlier in assemble.py, since the
    # sidebar's own content depends on every heading's final resolved id,
    # which only exists once the whole body has actually been rendered.
    final_html = (
        before
        + '<div class="page-layout">'
        + sidebar_html
        + '<div class="main-content">'
        + body_html
        + "</div></div>"
        + after
    )

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(final_html)

    print(f"Wrote {len(final_html)} characters to {out_path}")


if __name__ == "__main__":
    main()
